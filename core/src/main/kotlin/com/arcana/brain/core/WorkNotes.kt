package com.arcana.brain.core

import java.nio.file.Files

/**
 * The vault's view of the work log (proposals/0002): one generated Markdown note per kind, so the items can be read, searched and linked in Obsidian.
 * The log is the truth; these notes are written from it and are not read back (a hand edit is overwritten, and the note says so). Research is not here:
 * its lines are still in `Research/Research Backlog.md`, which is the truth for that kind until phase 5.
 */
object WorkNotes {
    /** The kinds that live in the log first, and where their note is. */
    val paths: Map<WorkKind, String> = mapOf(
        WorkKind.Todo to "Tasks/Todos.md",
        WorkKind.Question to "Questions/Questions.md",
    )

    /** The Markdown of [kind]'s note: its items by state, each line ending with its marker (`^w-…`) so Obsidian can link to it. [doneNotes]: the finished reports and answers. */
    fun render(kind: WorkKind, items: List<WorkItem>, doneNotes: Set<String> = emptySet(), backlogExists: Boolean = false): String = buildString {
        append("---\ntype: work\nkind: ${kind.id}\ntags: [index, work]\n---\n\n# ${kind.title}\n\n")
        append("Generated by Arcana from its work log: change an item in the Brain screen (`b`), not here; a change made in this note is overwritten.\n")
        val of = items.filter { it.kind == kind }
        for ((title, state) in listOf("Open" to WorkState.Open, "In progress" to WorkState.InProgress, "Done" to WorkState.Answered, "Given up" to WorkState.Abandoned)) {
            val group = of.filter { it.state(doneNotes) == state }
            if (group.isEmpty()) continue
            append("\n## $title\n\n")
            for (item in group) {
                val box = when (state) { WorkState.Answered -> "x"; WorkState.InProgress -> "~"; WorkState.Abandoned -> "-"; WorkState.Open -> " " }
                val notes = item.artifacts.joinToString(" ") { "[[${it.note}]]" }
                append("- [$box] ${item.text} (${item.date})${if (notes.isEmpty()) "" else " -> $notes"}${if (item.skill.isBlank()) "" else " · skill: ${item.skill}"} ^${item.id}\n")
            }
        }
        if (of.isEmpty()) append("\nNothing here yet.\n")
        // the notes of the work link to each other (and to the research backlog), so none of them is an island in the vault's own checks
        val related = ((if (backlogExists) listOf("Research Backlog") else emptyList()) + paths.values.map { it.substringAfterLast('/').removeSuffix(".md") }).filter { it != paths[kind]?.substringAfterLast('/')?.removeSuffix(".md") }
        append("\nRelated: ${related.joinToString(" · ") { "[[$it]]" }}\n")
    }

    /**
     * Writes the note of every kind in [paths] once any of them has items (or a note already exists), only when a text changed. Returns the paths it wrote.
     * Best effort for the caller: it throws on an I/O error.
     */
    fun sync(vault: Vault, store: WorkStore): List<String> {
        val items = store.items()
        val done = Reports.scan(vault).filter { it.status.equals("done", ignoreCase = true) }.map { it.title }.toSet()
        val written = ArrayList<String>()
        // all the notes are written together, as soon as one has something to show: each links to the others, and a link to a note that was not written would be a broken link
        val backlogExists = Files.exists(vault.root.resolve(ResearchBacklog.PATH))
        if (items.none { it.kind in paths.keys } && paths.values.none { Files.exists(vault.root.resolve(it)) }) return emptyList()
        for ((kind, path) in paths) {
            val file = vault.root.resolve(path)
            val text = render(kind, items, done, backlogExists)
            if (Files.exists(file) && Files.readString(file) == text) continue
            Files.createDirectories(file.parent)
            Files.writeString(file, text)
            written += path
        }
        return written
    }
}
